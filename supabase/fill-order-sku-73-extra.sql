-- (1) Argentum 4/10/30 ml: master มีแถวแต่ sku ว่าง — เติมโดยใช้ code ARM จาก 50ml เดิม
update product_barcodes
   set sku = 'ARM-' || (regexp_match(size,'([0-9]+)'))[1] || ' ml'
 where scent = 'Argentum' and coalesce(sku,'') = ''
   and (regexp_match(size,'([0-9]+)'))[1] in ('4','10','30');

